using BusBooking.Models;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
namespace BusBooking.Data;
public class AppDbContext(DbContextOptions<AppDbContext> options):IdentityDbContext<AppUser>(options) {
    public DbSet<TripStop> TripStops=>Set<TripStop>();
    public DbSet<ContactMessage> ContactMessages=>Set<ContactMessage>();
    public DbSet<BusRoute> Routes=>Set<BusRoute>();
    public DbSet<SeatLayout> Layouts=>Set<SeatLayout>();
    public DbSet<PhysicalSeat> PhysicalSeats=>Set<PhysicalSeat>();
    public DbSet<Vehicle> Vehicles=>Set<Vehicle>();
    public DbSet<Trip> Trips=>Set<Trip>();
    public DbSet<TripSeat> TripSeats=>Set<TripSeat>();
    public DbSet<SeatHold> SeatHolds=>Set<SeatHold>();
    public DbSet<HoldSeat> HoldSeats=>Set<HoldSeat>();
    public DbSet<Booking> Bookings=>Set<Booking>();
    public DbSet<Ticket> Tickets=>Set<Ticket>();
    public DbSet<PaymentEntry> Payments=>Set<PaymentEntry>();
    public DbSet<ChangeRequest> ChangeRequests=>Set<ChangeRequest>();
    public DbSet<AuditEntry> AuditEntries=>Set<AuditEntry>();
    protected override void OnModelCreating(ModelBuilder b) {
        base.OnModelCreating(b);
        b.Entity<AppUser>().Property(x=>x.CreatedUtc).HasDefaultValueSql("SYSUTCDATETIME()");
        ContactModelV1.Build(b);
        b.Entity<Microsoft.AspNetCore.Identity.IdentityUserLogin<string>>().Property(x=>x.LoginProvider).HasMaxLength(128);
        b.Entity<Microsoft.AspNetCore.Identity.IdentityUserLogin<string>>().Property(x=>x.ProviderKey).HasMaxLength(128);
        b.Entity<Microsoft.AspNetCore.Identity.IdentityUserToken<string>>().Property(x=>x.LoginProvider).HasMaxLength(128);
        b.Entity<Microsoft.AspNetCore.Identity.IdentityUserToken<string>>().Property(x=>x.Name).HasMaxLength(128);
        b.Entity<BusRoute>().Ignore(x=>x.Label);
        b.Entity<BusRoute>().HasIndex(x=>new{x.Origin,x.Destination}).IsUnique();
        b.Entity<BusRoute>().ToTable("Routes",t=>t.HasCheckConstraint("CK_Route_Duration","[DurationMinutes] > 0 AND [Origin] <> [Destination]"));
        b.Entity<SeatLayout>().HasMany(x=>x.Seats).WithOne(x=>x.Layout).HasForeignKey(x=>x.SeatLayoutId);
        b.Entity<SeatLayout>().ToTable("Layouts",t=>t.HasCheckConstraint("CK_Layout_Shape","[Rows] BETWEEN 1 AND 20 AND [Columns] BETWEEN 1 AND 4 AND [Floors] BETWEEN 1 AND 2"));
        b.Entity<PhysicalSeat>().HasIndex(x=>new{x.SeatLayoutId,x.Code}).IsUnique();
        b.Entity<PhysicalSeat>().HasIndex(x=>new{x.SeatLayoutId,x.Floor,x.Row,x.Column}).IsUnique();
        b.Entity<PhysicalSeat>().ToTable("PhysicalSeats",t=>t.HasCheckConstraint("CK_PhysicalSeat_Position","[Row]>0 AND [Column]>0 AND [Floor]>0"));
        b.Entity<Vehicle>().HasIndex(x=>x.Plate).IsUnique();
        b.Entity<Vehicle>().Property(x=>x.Kind).HasConversion<string>().HasMaxLength(12);
        b.Entity<Vehicle>().ToTable("Vehicles",t=>t.HasCheckConstraint("CK_Vehicle_Kind","[Kind] IN ('Seated','Sleeper')"));
        b.Entity<Vehicle>().HasOne(x=>x.Layout).WithMany().HasForeignKey(x=>x.SeatLayoutId);
        b.Entity<Trip>().HasOne(x=>x.Route).WithMany().HasForeignKey(x=>x.BusRouteId);
        b.Entity<Trip>().HasOne(x=>x.Vehicle).WithMany().HasForeignKey(x=>x.VehicleId);
        b.Entity<Trip>().HasOne(x=>x.Driver).WithMany().HasForeignKey(x=>x.DriverId);
        b.Entity<Trip>().HasOne(x=>x.CoDriver).WithMany().HasForeignKey(x=>x.CoDriverId);
        b.Entity<Trip>().HasIndex(x=>new{x.CoDriverId,x.DepartureUtc,x.ArrivalUtc});
        b.Entity<Trip>().HasOne(x=>x.Staff).WithMany().HasForeignKey(x=>x.StaffId);
        b.Entity<Trip>().Property(x=>x.Fare).HasPrecision(18,2);
        b.Entity<Trip>().Property(x=>x.Status).HasConversion<string>().HasMaxLength(20);
        b.Entity<Trip>().HasIndex(x=>new{x.BusRouteId,x.DepartureUtc,x.Status,x.SalesOpen});
        b.Entity<Trip>().HasIndex(x=>new{x.VehicleId,x.DepartureUtc,x.ArrivalUtc});
        b.Entity<Trip>().HasIndex(x=>new{x.DriverId,x.DepartureUtc,x.ArrivalUtc});
        b.Entity<Trip>().ToTable("Trips",t=>t.HasCheckConstraint("CK_Trip_Values","[ArrivalUtc]>[DepartureUtc] AND [Fare]>=0 AND [Revision]>=0 AND [Status] IN ('Scheduled','Boarding','InProgress','Completed','Cancelled')"));
        b.Entity<TripSeat>().HasOne(x=>x.Trip).WithMany(x=>x.Seats).HasForeignKey(x=>x.TripId);
        b.Entity<TripSeat>().HasOne(x=>x.PhysicalSeat).WithMany().HasForeignKey(x=>x.PhysicalSeatId);
        b.Entity<TripSeat>().HasOne(x=>x.CurrentHold).WithMany().HasForeignKey(x=>new{x.CurrentHoldId,x.TripId}).HasPrincipalKey(x=>new{x.Id,x.TripId});
        b.Entity<TripSeat>().HasIndex(x=>new{x.TripId,x.PhysicalSeatId}).IsUnique();
        b.Entity<TripSeat>().HasIndex(x=>new{x.TripId,x.Code}).IsUnique();
        b.Entity<TripSeat>().HasAlternateKey(x=>new{x.Id,x.TripId});
        b.Entity<TripSeat>().HasIndex(x=>new{x.TripId,x.Status});
        b.Entity<TripSeat>().Property(x=>x.Status).HasConversion<string>().HasMaxLength(12);
        b.Entity<TripSeat>().ToTable("TripSeats",t=>t.HasCheckConstraint("CK_TripSeat_State","([Status]='Held' AND [CurrentHoldId] IS NOT NULL) OR ([Status] IN ('Available','Booked') AND [CurrentHoldId] IS NULL)"));
        b.Entity<SeatHold>().HasAlternateKey(x=>new{x.Id,x.TripId});
        b.Entity<SeatHold>().HasOne(x=>x.Trip).WithMany().HasForeignKey(x=>x.TripId);
        b.Entity<SeatHold>().HasOne(x=>x.Owner).WithMany().HasForeignKey(x=>x.OwnerId);
        b.Entity<SeatHold>().HasIndex(x=>new{x.OwnerId,x.RequestKey}).IsUnique();
        b.Entity<SeatHold>().HasIndex(x=>new{x.Status,x.ExpiresAtUtc,x.TripId});
        b.Entity<SeatHold>().Property(x=>x.Status).HasConversion<string>().HasMaxLength(12);
        b.Entity<SeatHold>().ToTable("SeatHolds",t=>t.HasCheckConstraint("CK_Hold_Expiry","[ExpiresAtUtc]>[CreatedUtc] AND [Status] IN ('Active','Released','Expired','Confirmed')"));
        b.Entity<HoldSeat>().HasKey(x=>new{x.SeatHoldId,x.TripSeatId});
        b.Entity<HoldSeat>().HasOne(x=>x.Hold).WithMany(x=>x.Items).HasForeignKey(x=>new{x.SeatHoldId,x.TripId}).HasPrincipalKey(x=>new{x.Id,x.TripId});
        b.Entity<HoldSeat>().HasOne(x=>x.Seat).WithMany().HasForeignKey(x=>new{x.TripSeatId,x.TripId}).HasPrincipalKey(x=>new{x.Id,x.TripId});
        b.Entity<Booking>().HasOne(x=>x.Hold).WithMany().HasForeignKey(x=>x.SeatHoldId);
        b.Entity<Booking>().HasOne(x=>x.Owner).WithMany().HasForeignKey(x=>x.OwnerId);
        b.Entity<Booking>().HasIndex(x=>x.SeatHoldId).IsUnique();
        b.Entity<Booking>().HasIndex(x=>x.Code).IsUnique();
        b.Entity<Booking>().HasIndex(x=>new{x.OwnerId,x.CreatedUtc});
        b.Entity<Booking>().HasIndex(x=>new{x.Status,x.CreatedUtc});
        b.Entity<Booking>().Property(x=>x.Status).HasConversion<string>().HasMaxLength(12);
        b.Entity<Booking>().Property(x=>x.Total).HasPrecision(18,2);
        b.Entity<Booking>().Property(x=>x.SimulatedPaidAmount).HasPrecision(18,2);
        b.Entity<Booking>().Ignore(x=>x.Balance);
        b.Entity<Booking>().HasIndex(x=>new{x.Status,x.PaymentExpiresUtc}).HasFilter("[PaymentExpiresUtc] IS NOT NULL");
        b.Entity<Booking>().HasOne<Booking>().WithMany().HasForeignKey(x=>x.ReplacesBookingId);
        b.Entity<Booking>().ToTable("Bookings",t=>{
            t.HasCheckConstraint("CK_Booking_Total","[Total]>=0 AND [Status] IN ('Active','Cancelled','Exchanged','Expired')");
            t.HasCheckConstraint("CK_Booking_SimulatedPayment","([SimulatedPaidUtc] IS NULL AND [SimulatedPaidAmount] IS NULL) OR ([SimulatedPaidUtc] IS NOT NULL AND [SimulatedPaidAmount] IS NOT NULL AND [SimulatedPaidAmount]>0 AND [SimulatedPaidAmount]<=[Total])");
        });
        b.Entity<Ticket>().HasOne(x=>x.Booking).WithMany(x=>x.Tickets).HasForeignKey(x=>x.BookingId);
        b.Entity<Ticket>().HasOne(x=>x.Seat).WithMany().HasForeignKey(x=>x.TripSeatId);
        b.Entity<Ticket>().HasIndex(x=>x.TripSeatId).IsUnique().HasFilter("[IsActive] = 1");
        b.Entity<Ticket>().Property(x=>x.Fare).HasPrecision(18,2);
        b.Entity<Ticket>().ToTable("Tickets",t=>t.HasCheckConstraint("CK_Ticket_Fare","[Fare]>=0"));
        b.Entity<PaymentEntry>().HasOne(x=>x.Booking).WithMany(x=>x.Payments).HasForeignKey(x=>x.BookingId);
        b.Entity<PaymentEntry>().Property(x=>x.Amount).HasPrecision(18,2);
        b.Entity<PaymentEntry>().Property(x=>x.Kind).HasConversion<string>().HasMaxLength(12);
        b.Entity<PaymentEntry>().HasIndex(x=>new{x.ActorId,x.RequestKey}).IsUnique();
        b.Entity<PaymentEntry>().HasIndex(x=>x.CreatedUtc);
        b.Entity<PaymentEntry>().ToTable("Payments",t=>t.HasCheckConstraint("CK_Payment_Sign","([Kind]='Receipt' AND [Amount]>0) OR ([Kind]='Refund' AND [Amount]<0)"));
        b.Entity<ChangeRequest>().HasOne(x=>x.Booking).WithMany().HasForeignKey(x=>x.BookingId);
        b.Entity<ChangeRequest>().Property(x=>x.Kind).HasConversion<string>().HasMaxLength(12);
        b.Entity<ChangeRequest>().Property(x=>x.Status).HasConversion<string>().HasMaxLength(12);
        b.Entity<ChangeRequest>().HasIndex(x=>x.BookingId).IsUnique().HasFilter("[Status] = 'Pending'");
        b.Entity<AuditEntry>().HasIndex(x=>new{x.Action,x.CreatedUtc});
        StopModelV1.Build(b);
        // Keep transactional history. No cascade path deletes Identity, vehicles or tickets.
        foreach(var fk in b.Model.GetEntityTypes().SelectMany(e=>e.GetForeignKeys())) fk.DeleteBehavior=DeleteBehavior.Restrict;
    }
}
